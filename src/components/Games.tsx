interface BubbleType {
  id: number;
  x: number; // percentage
  y: number; // pixels
  speed: number;
  type: 'toxic' | 'mindful';
  emoji: string;
  titleEn: string;
  titleFa: string;
}

function PopperGame({ isEn, soundEnabled, highScore, saveHighScore, awardXp }: {
  isEn: boolean;
  soundEnabled: boolean;
  highScore: number;
  saveHighScore: (gameId: string, score: number) => boolean;
  awardXp: (amount: number) => void;
}) {
  const [gameState, setGameState] = useState<'idle' | 'playing' | 'ended'>('idle');
  const [score, setScore] = useState(0);
  const [lives, setLives] = useState(3);
  const [bubbles, setBubbles] = useState<BubbleType[]>([]);
  const [difficulty, setDifficulty] = useState<'easy' | 'medium' | 'hard'>('medium');

  const TOXIC_PRESETS = [
    { emoji: '📉', titleEn: 'Procrastination', titleFa: 'اهمال‌کاری' },
    { emoji: '😵', titleEn: 'Overthinking', titleFa: 'نشخوار ذهنی' },
    { emoji: '🍩', titleEn: 'Junk Food', titleFa: 'شکر مفرط' },
    { emoji: '😡', titleEn: 'Anger / Pride', titleFa: 'خشم روزانه' },
    { emoji: '📱', titleEn: 'Doomscrolling', titleFa: 'هرزگردی وب' },
    { emoji: '🛑', titleEn: 'Excuses', titleFa: 'بهانه‌تراشی' }
  ];

  const MINDFUL_PRESETS = [
    { emoji: '🙏', titleEn: 'Gratitude', titleFa: 'شکرگزاری' },
    { emoji: '🧘', titleEn: 'Breath Anchor', titleFa: 'دم عمیق' },
    { emoji: '💧', titleEn: 'Drink Water', titleFa: 'نوشیدن آب' },
    { emoji: '📚', titleEn: 'Read Book', titleFa: 'مطالعه کتاب' },
    { emoji: '🤸', titleEn: 'Stretch', titleFa: 'کشش عضلات' },
    { emoji: '💤', titleEn: 'Silent Sleep', titleFa: 'خواب آرام' }
  ];

  const scoreRef = useRef(score);
  useEffect(() => {
    scoreRef.current = score;
  }, [score]);

  const initGame = () => {
    setScore(0);
    setLives(3);
    setBubbles([]);
    setGameState('playing');
  };

  useEffect(() => {
    if (gameState !== 'playing') return;

    const gameTicker = setInterval(() => {
      setBubbles(prev => {
        let isPenalty = false;
        const updated = prev.map(b => ({ ...b, y: b.y - b.speed }));

        const filtered: BubbleType[] = [];
        for (const b of updated) {
          if (b.y <= 12) {
            if (b.type === 'toxic') {
              isPenalty = true;
            } else {
              setScore(s => s + 5);
            }
          } else {
            filtered.push(b);
          }
        }

        if (isPenalty) {
          setLives(l => {
            const nextVal = l - 1;
            if (nextVal <= 0) {
              setGameState('ended');
            }
            return nextVal;
          });
          if (soundEnabled) {
            sounds.play('retro');
          }
        }

        return filtered;
      });
    }, 45);

    const spawner = setInterval(() => {
      const scoreVal = scoreRef.current;
      
      let spawnCount = 1;
      if (difficulty === 'easy') {
        spawnCount = Math.random() < 0.35 ? 2 : 1;
      } else if (difficulty === 'medium') {
        spawnCount = Math.random() < 0.5 ? 2 : 3;
      } else {
        spawnCount = Math.floor(Math.random() * 3) + 3; // 3, 4, or 5 bubbles at once!
      }

      const speedMultiplier = difficulty === 'easy' ? 0.6 : difficulty === 'medium' ? 1.0 : 1.7;
      const extraMultiplier = difficulty === 'easy' ? 0.6 : difficulty === 'medium' ? 1.0 : 1.5;

      const newBubbles: BubbleType[] = [];

      for (let i = 0; i < spawnCount; i++) {
        const isToxic = Math.random() < 0.55;
        const arr = isToxic ? TOXIC_PRESETS : MINDFUL_PRESETS;
        const tItem = arr[Math.floor(Math.random() * arr.length)];
        
        const baseSpeed = (isToxic ? 1.6 : 1.3) * speedMultiplier;
        const speed = baseSpeed + (Math.random() * 1.4 + Math.min(2.8, scoreVal * 0.015)) * extraMultiplier;

        // Space out horizontal positions beautifully to minimize overlaps between bubbles
        const minX = 8;
        const maxX = 86;
        const step = (maxX - minX) / spawnCount;
        const xOffset = minX + (step * i) + (Math.random() * (step * 0.8));

        const newBubble: BubbleType = {
          id: Date.now() + Math.random() + i * 0.001,
          x: Math.min(maxX, Math.max(minX, xOffset)),
          y: 330 + (Math.random() * 25), // stagger starting heights for a natural wave effect
          speed,
          type: isToxic ? 'toxic' : 'mindful',
          emoji: tItem.emoji,
          titleEn: tItem.titleEn,
          titleFa: tItem.titleFa
        };
        newBubbles.push(newBubble);
      }

      setBubbles(prev => [...prev, ...newBubbles]);
    }, difficulty === 'easy' ? 1800 : difficulty === 'medium' ? 1500 : 1100);

    return () => {
      clearInterval(gameTicker);
      clearInterval(spawner);
    };
  }, [gameState, difficulty]);

  const handleBubbleClick = (bId: number, type: 'toxic' | 'mindful') => {
    if (gameState !== 'playing') return;

    if (soundEnabled) {
      sounds.play('click');
    }

    setBubbles(prev => prev.filter(b => b.id !== bId));

    if (type === 'toxic') {
      setScore(s => s + 10);
    } else {
      setLives(l => {
        const nextVal = l - 1;
        if (nextVal <= 0) {
          setGameState('ended');
        }
        return nextVal;
      });
      if (soundEnabled) {
        sounds.play('retro');
      }
    }
  };

  useEffect(() => {
    if (gameState === 'ended') {
      saveHighScore('popper', score);
      awardXp(Math.min(30, Math.floor(score * 0.15)));
    }
  }, [gameState]);

  return (
    <div className="w-full flex flex-col items-center gap-4 text-center">
      <div className="flex justify-between w-full items-center font-sans">
        <span className="text-xs text-app-muted font-bold block">
          {isEn ? `Personal Best: ${highScore} pts` : `رکورد شخصی: ${highScore}`}
        </span>
        
        {gameState === 'playing' && (
          <div className="flex items-center gap-1 bg-app-widget border border-app-border px-3 py-1 rounded-xl">
            {Array.from({ length: 3 }).map((_, idx) => (
              <span key={idx} className={`text-sm ${idx < lives ? 'text-rose-500 saturate-100 opacity-100' : 'text-app-muted opacity-25'}`}>
                ❤️
              </span>
            ))}
          </div>
        )}

        <span className="text-xs bg-rose-500/10 text-rose-500 border border-rose-500/20 px-2.5 py-1 rounded-full font-black">
          {isEn ? `Score: ${score}` : `امتیاز: ${score}`}
        </span>
      </div>

      {gameState === 'idle' && (
        <div className="flex flex-col items-center gap-4 py-8 max-w-sm font-sans animate-in fade-in zoom-in-95 duration-200">
          <span className="text-4xl animate-pulse">🎈💥</span>
          <h3 className="font-sans font-black text-base text-app-text">
            {isEn ? 'Stress Buster Reflex Popper' : 'شکارچی تنش و اضطراب ذهنی'}
          </h3>
          <p className="text-xs text-app-muted leading-relaxed">
            {isEn 
              ? 'Pop the floating toxic red stress bubbles before they reach your focus limit. Let the calm, positive mindful anchors rise into your sub-conscious!'
              : 'یک بازی تفننی و رکوردزنی عصب‌شناختی عادتیار! حباب‌ها از پایین به سمت بالا شناور می‌شوند. فقط بر روی حباب‌های مضر (قرمز عصبانی) کلیک کنید تا متلاشی شوند، اما بگذارید حباب‌های مثبت عافیت با موفقیت پرواز کنند.'}
          </p>

          {/* Difficulty Selector */}
          <div className="flex flex-col gap-2 w-full max-w-[280px] mt-2 mb-1">
            <span className="text-xs font-bold text-app-muted">
              {isEn ? 'Select Difficulty Level:' : 'انتخاب سطح دشواری بازی:'}
            </span>
            <div className="grid grid-cols-3 gap-1.5 p-1 bg-app-widget border border-app-border rounded-xl">
              <button
                type="button"
                onClick={(e) => {
                  e.preventDefault();
                  e.stopPropagation();
                  setDifficulty('easy');
                }}
                className={`py-1.5 rounded-lg text-xs font-bold transition-all cursor-pointer ${
                  difficulty === 'easy'
                    ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/45 scale-105 shadow-sm font-black'
                    : 'text-app-muted hover:text-app-text bg-transparent'
                }`}
              >
                {isEn ? 'Easy' : 'ساده'}
              </button>
              <button
                type="button"
                onClick={(e) => {
                  e.preventDefault();
                  e.stopPropagation();
                  setDifficulty('medium');
                }}
                className={`py-1.5 rounded-lg text-xs font-bold transition-all cursor-pointer ${
                  difficulty === 'medium'
                    ? 'bg-amber-500/20 text-amber-400 border border-amber-500/45 scale-105 shadow-sm font-black'
                    : 'text-app-muted hover:text-app-text bg-transparent'
                }`}
              >
                {isEn ? 'Medium' : 'متوسط'}
              </button>
              <button
                type="button"
                onClick={(e) => {
                  e.preventDefault();
                  e.stopPropagation();
                  setDifficulty('hard');
                }}
                className={`py-1.5 rounded-lg text-xs font-bold transition-all cursor-pointer ${
                  difficulty === 'hard'
                    ? 'bg-rose-500/20 text-rose-400 border border-rose-500/45 scale-105 shadow-sm font-black'
                    : 'text-app-muted hover:text-app-text bg-transparent'
                }`}
              >
                {isEn ? 'Hard' : 'سخت'}
              </button>
            </div>
            <span className="text-[10px] text-app-brand font-black mt-0.5">
              {difficulty === 'easy' && (isEn ? '🐢 Bubbles rise smoothly & gently' : '🐢 حرکت آرام و ملایم حباب‌ها')}
              {difficulty === 'medium' && (isEn ? '⚡ Standard focus reflexes required' : '⚡ نیازمند واکنش‌های استاندارد و تمرکز')}
              {difficulty === 'hard' && (isEn ? '🔥 Ultra fast! Ultimate reflex challenge' : '🔥 فوق العاده سریع! نهایت چالش تمرکز و سرعت عمل')}
            </span>
          </div>

          <button
            type="button"
            onClick={(e) => {
              e.preventDefault();
              e.stopPropagation();
              initGame();
            }}
            className="mt-2 px-6 py-2.5 bg-rose-500 hover:bg-rose-600 font-black text-xs text-white rounded-xl shadow-md transition-all cursor-pointer hover:scale-105"
          >
            {isEn ? 'Start Busting Stress' : 'شروع پاکسازی ذهن'}
          </button>
        </div>
      )}

      {gameState === 'playing' && (
        <div className="flex flex-col items-center gap-3 w-full font-sans font-sans">
          <div className="text-[10px] text-app-brand font-black animate-pulse flex items-center gap-1.5 justify-center">
            <span>🎯</span>
            <span>{isEn ? 'Click Only Negative Stressors!' : 'فقط روی حباب‌های استرس‌زا کلیک فرمایید!'}</span>
          </div>

          <div className="w-full max-w-[340px] h-[350px] bg-app-widget/40 border border-app-border rounded-3xl relative overflow-hidden flex items-center justify-center">
            <div className="absolute top-0 inset-x-0 h-3.5 bg-gradient-to-b from-rose-500/20 to-transparent pointer-events-none border-b border-rose-500/10" />
            
            {bubbles.length === 0 && (
              <span className="text-[10px] text-app-muted font-bold font-sans animate-pulse">
                {isEn ? 'Calm mind - Waiting for focus waves...' : 'ذهن آرام - در انتظار جریان‌ها...'}
              </span>
            )}

            {bubbles.map(b => (
              <button
                key={b.id}
                type="button"
                onClick={(e) => {
                  e.preventDefault();
                  e.stopPropagation();
                  handleBubbleClick(b.id, b.type);
                }}
                className={`absolute w-[44px] h-[44px] rounded-full border-2 flex flex-col items-center justify-center text-center cursor-pointer shadow-lg active:scale-95 transition-all text-[8px] animate-in zoom-in-30 duration-75 select-none ${
                  b.type === 'toxic'
                    ? 'bg-rose-500/10 hover:bg-rose-500/20 border-rose-500/40 text-rose-300'
                    : 'bg-emerald-500/10 hover:bg-emerald-500/20 border-emerald-500/40 text-emerald-300'
                }`}
                style={{
                  left: `${b.x}%`,
                  bottom: `${350 - b.y}px`
                }}
              >
                <span className="text-sm select-none pointer-events-none line-none">{b.emoji}</span>
                <span className="text-[6px] tracking-tight font-black leading-none pointer-events-none opacity-80 mt-0.5 select-none text-center truncate max-w-[40px] text-app-text">
                  {isEn ? b.titleEn : b.titleFa}
                </span>
                <span className="absolute inset-0 border border-white/5 bg-transparent rounded-full pointer-events-none animate-ping opacity-15" />
              </button>
            ))}
          </div>

          <div className="flex justify-between items-center w-full max-w-[340px] text-[9px] text-app-muted px-1.5 font-bold font-sans">
            <span>🔴 {isEn ? 'Red = Pop!' : 'قرمز = لمس / پاپ!'}</span>
            <span>🟢 {isEn ? 'Green = Let Float' : 'سبز = پرواز آرامش'}</span>
          </div>
        </div>
      )}

      {gameState === 'ended' && (
        <div className="flex flex-col items-center gap-4 py-8 max-w-sm font-sans">
          <span className="text-4xl text-rose-500">🎮</span>
          <h3 className="font-sans font-black text-base text-app-text">
            {isEn ? 'Buster Complete!' : 'پایان بازی پاکسازی تنش'}
          </h3>
          <p className="text-xs text-app-muted">
            {isEn 
              ? `You busted stressors successfully with a score of ${score} pts!` 
              : `عملکرد مهار تنش‌های محیطی شما با کسب امتیاز ${score} پایان یافت.`}
          </p>
          <div className="bg-app-widget border border-app-border rounded-xl p-3 w-full flex items-center justify-between text-xs font-sans">
            <span className="text-app-muted">{isEn ? 'XP Earned Today:' : 'امتیاز کسب‌شده لول:'}</span>
            <span className="text-rose-500 font-bold">+{Math.min(30, Math.floor(score * 0.15))} XP</span>
          </div>

          <button
            type="button"
            onClick={(e) => {
              e.preventDefault();
              e.stopPropagation();
              initGame();
            }}
            className="px-6 py-2.5 bg-rose-500 hover:bg-rose-600 font-white text-xs font-black text-white rounded-xl shadow-md transition-all cursor-pointer flex items-center gap-1 hover:scale-105"
          >
            <RotateCcw size={12} />
            <span>{isEn ? 'Try Again' : 'تلاش مجدد'}</span>
          </button>
        </div>
      )}
    </div>
  );
}
