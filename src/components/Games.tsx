// COMPONENT: GA-5 ATOM HABITS COMPOUND 2048
// ============================================
function Puzzle2048Game({ isEn, soundEnabled, highScore, saveHighScore, awardXp }: {
  isEn: boolean;
  soundEnabled: boolean;
  highScore: number;
  saveHighScore: (gameId: string, score: number) => boolean;
  awardXp: (amount: number) => void;
}) {
  const MAX_TIME = 20;

  const HABIT_OBSTACLES = [
    { emoji: '😴', titleEn: 'Laziness', titleFa: 'تنبلی', color: 'from-orange-600/30 to-red-600/30 text-orange-200 border-orange-500/40' },
    { emoji: '📱', titleEn: 'Social Scrolling', titleFa: 'پرسبگردی دیجیتال', color: 'from-pink-600/30 to-rose-600/30 text-rose-200 border-pink-500/40' },
    { emoji: '🍟', titleEn: 'Junk Food', titleFa: 'تغذیه ناسالم', color: 'from-yellow-600/30 to-amber-600/30 text-amber-200 border-amber-500/40' },
    { emoji: '⏳', titleEn: 'Procrastination', titleFa: 'اهمال‌کاری', color: 'from-purple-600/30 to-indigo-600/30 text-purple-200 border-purple-500/40' },
    { emoji: '🌪️', titleEn: 'Distractions', titleFa: 'حواس‌پرتی', color: 'from-cyan-600/30 to-blue-600/30 text-cyan-200 border-cyan-500/40' },
    { emoji: '🚬', titleEn: 'Bad Habits', titleFa: 'عادات مخرب', color: 'from-stone-600/30 to-zinc-600/30 text-zinc-200 border-zinc-500/40' },
  ];

  interface BlockType {
    id: number;
    habitType: typeof HABIT_OBSTACLES[0];
    obstacle: 'left' | 'right' | 'none';
  }

  interface FlyingBlockType {
    id: number;
    habitType: typeof HABIT_OBSTACLES[0];
    startX: number;
    flyX: number;
    flyY: number;
    rotate: number;
  }

  const [gameState, setGameState] = useState<'idle' | 'playing' | 'ended'>('idle');
  const [score, setScore] = useState(0);
  const [timeLeft, setTimeLeft] = useState(MAX_TIME);
  const [blocks, setBlocks] = useState<BlockType[]>([]);
  const [boxerSide, setBoxerSide] = useState<'left' | 'right'>('left');
  const [boxerState, setBoxerState] = useState<'idle' | 'punching'>('idle');
  const [flyingBlocks, setFlyingBlocks] = useState<FlyingBlockType[]>([]);

  // Keep a mutable ref to score to avoid interval closures having stale scores
  const scoreRef = useRef(score);
  useEffect(() => {
    scoreRef.current = score;
  }, [score]);

  // Handle Game Over
  const triggerGameOver = () => {
    if (soundEnabled) {
      sounds.play('retro');
    }
    setGameState('ended');
    saveHighScore('puzzle2048', scoreRef.current);
    awardXp(Math.min(50, Math.floor(scoreRef.current * 0.4)));
  };

  const generateNextBlock = (prevBlock?: BlockType): BlockType => {
    let candidateObstacle: 'left' | 'right' | 'none' = 'none';
    
    if (prevBlock) {
      const lastObs = prevBlock.obstacle;
      if (lastObs === 'left') {
        // If previous was 'left', the next block can only be 'left' or 'none' (never 'right')
        candidateObstacle = Math.random() < 0.45 ? 'left' : 'none';
      } else if (lastObs === 'right') {
        // If previous was 'right', the next block can only be 'right' or 'none' (never 'left')
        candidateObstacle = Math.random() < 0.45 ? 'right' : 'none';
      } else {
        // If previous was 'none', any obstacle can spawn
        const rand = Math.random();
        if (rand < 0.35) {
          candidateObstacle = 'left';
        } else if (rand < 0.70) {
          candidateObstacle = 'right';
        } else {
          candidateObstacle = 'none';
        }
      }
    }

    return {
      id: Date.now() + Math.random(),
      habitType: HABIT_OBSTACLES[Math.floor(Math.random() * HABIT_OBSTACLES.length)],
      obstacle: candidateObstacle
    };
  };

  const initGame = () => {
    const initialBlocks: BlockType[] = [];
    
    // Create first 3 blocks completely safe to give a gentle start
    for (let i = 0; i < 3; i++) {
      initialBlocks.push({
        id: Date.now() + i,
        habitType: HABIT_OBSTACLES[Math.floor(Math.random() * HABIT_OBSTACLES.length)],
        obstacle: 'none'
      });
    }

    // Populate remaining 3 blocks using the smart generator
    for (let i = 3; i < 6; i++) {
      const prevBlock = initialBlocks[initialBlocks.length - 1];
      initialBlocks.push(generateNextBlock(prevBlock));
    }

    setBlocks(initialBlocks);
    setScore(0);
    setTimeLeft(MAX_TIME);
    setBoxerSide('left');
    setBoxerState('idle');
    setFlyingBlocks([]);
    setGameState('playing');
  };

  // Ticking countdown effect with dynamic decay as score goes higher!
  useEffect(() => {
    if (gameState !== 'playing') return;

    const timer = setInterval(() => {
      setTimeLeft(prev => {
        // As score goes higher, decay happens progressively faster
        const decayMultiplier = 1.0 + Math.min(8.0, scoreRef.current * 0.08);
        const nextVal = prev - (0.05 * decayMultiplier);
        
        if (nextVal <= 0) {
          triggerGameOver();
          return 0;
        }
        return nextVal;
      });
    }, 50);

    return () => clearInterval(timer);
  }, [gameState]);

  // Execute punch from either Left or Right
  const handlePunch = (side: 'left' | 'right') => {
    if (gameState !== 'playing') {
      if (gameState === 'idle') {
        initGame();
      }
      return;
    }

    // 1. Move player to the designated punch side & trigger brief animation feel
    setBoxerSide(side);
    setBoxerState('punching');
    setTimeout(() => {
      setBoxerState('idle');
    }, 70);

    // RULE A: Check if current block at chest level (blocks[1]) has an obstacle on our side.
    // If so, player hits/collides with the branch immediately.
    const currentHeartBlock = blocks[1];
    if (currentHeartBlock && currentHeartBlock.obstacle === side) {
      triggerGameOver();
      return;
    }

    const bottomBlock = blocks[0];
    if (!bottomBlock) return;

    // 2. Play sound & add particles (flying block)
    if (soundEnabled) {
      sounds.play('wood');
    }

    const directionMultiplier = side === 'left' ? 1 : -1;
    const newFlying: FlyingBlockType = {
      id: Date.now() + Math.random(),
      habitType: bottomBlock.habitType,
      startX: side === 'left' ? -20 : 20,
      flyX: directionMultiplier * (150 + Math.random() * 80),
      flyY: -100 - Math.random() * 100,
      rotate: directionMultiplier * (180 + Math.random() * 180)
    };

    setFlyingBlocks(prev => [...prev.filter(f => Date.now() - f.id < 500), newFlying]);

    // 3. Increment score
    const nextScore = scoreRef.current + 1;
    setScore(nextScore);

    // 4. Update Time Left (adds time but gets narrower/harder over time)
    setTimeLeft(prev => {
      const addedTime = Math.max(0.15, 1.25 - nextScore * 0.012);
      return Math.min(MAX_TIME, prev + addedTime);
    });

    // 5. Shift blocks down, append a smart generated new block inside list
    setBlocks(prev => {
      const nextBlocks = [...prev];
      nextBlocks.shift(); // pop bottom (blocks[0] is removed)

      // Get the current top-most block of the remaining stack
      const lastBlock = nextBlocks[nextBlocks.length - 1];
      const nextBlock = generateNextBlock(lastBlock);
      nextBlocks.push(nextBlock);

      // RULE B: After the shift, the old blocks[2] has now dropped down to blocks[1] (chest level).
      // Check if this newly dropped chest-level block has an obstacle on "side".
      // If so, the branch falls onto player's head immediately!
      if (nextBlocks[1] && nextBlocks[1].obstacle === side) {
        setTimeout(() => triggerGameOver(), 10);
      }

      return nextBlocks;
    });
  };

  // Keyboard Event Hooks
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (gameState !== 'playing') return;
      if (e.key === 'ArrowLeft') {
        e.preventDefault();
        handlePunch('left');
      } else if (e.key === 'ArrowRight') {
        e.preventDefault();
        handlePunch('right');
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [gameState, blocks]);

  return (
    <div className="w-full flex flex-col items-center gap-4 text-center select-none">
      <div className="flex justify-between w-full items-center px-1">
        <span className="text-xs text-app-muted font-bold font-sans">
          {isEn ? `Record: ${highScore} pts` : `بیشترین رکورد: ${highScore}`}
        </span>
        <span className="text-xs bg-yellow-500/10 text-yellow-500 border border-yellow-500/20 px-2.5 py-1 rounded-full font-black font-sans">
          {isEn ? `Score: ${score}` : `امتیاز عادات: ${score}`}
        </span>
      </div>

      {gameState === 'idle' && (
        <div className="flex flex-col items-center gap-4 py-8 max-w-sm font-sans animate-in fade-in zoom-in-95 duration-200">
          <span className="text-4xl animate-bounce">🥊🧱⚡</span>
          <h3 className="font-sans font-black text-base text-app-text">
            {isEn ? 'Fighter Habit Tower Smash' : 'سلاطین تمرکز: برج‌شکن عادات'}
          </h3>
          <p className="text-xs text-app-muted leading-relaxed">
            {isEn 
              ? 'Punch and smash bad habits! Stay alert: avoid the incoming danger barrier shelves protruding on Left or Right. Keep your punch velocity high to sustain the timer bar!'
              : 'تمرکز نینجا عادات! موانع عادات بد را پی‌در‌پی درهم بکوبید. مراقب باشید طبقات فرعی برج روی سر قهرمان فرود نیاید وگرنه می‌بازد! سرعت ضربه بالا باعث زنده ماندن تایمر می‌شود.'}
          </p>
          <button
            type="button"
            onClick={initGame}
            className="mt-2 px-6 py-2.5 bg-yellow-500 hover:bg-yellow-600 font-black text-xs text-black rounded-xl shadow-md transition-all cursor-pointer hover:scale-105"
          >
            {isEn ? 'Start Smashing' : 'شروع نبرد عادات'}
          </button>
        </div>
      )}

      {gameState === 'playing' && (
        <div className="flex flex-col items-center gap-2 w-full font-sans">
          
          {/* Dynamic timer progress line */}
          <div className="flex items-center gap-2 w-full max-w-[280px]">
            <span className="text-xs">⏳</span>
            <div className="flex-1 h-3 bg-zinc-950 border border-app-border rounded-full overflow-hidden relative shadow-inner">
              <div 
                className="h-full bg-gradient-to-r from-red-500 via-amber-400 to-emerald-400 transition-all duration-75"
                style={{ width: `${(timeLeft / MAX_TIME) * 100}%` }}
              />
            </div>
            <span className="text-[10px] font-mono font-black text-app-muted">
              {Math.max(0, timeLeft).toFixed(1)}s
            </span>
          </div>

          {/* Active Gaming Stage */}
          <div className="relative w-[300px] md:w-[320px] h-[350px] bg-zinc-900/60 border border-app-border rounded-2xl overflow-hidden mt-2 p-1">
            
            {/* Ambient Background Grid lines */}
            <div className="absolute inset-0 bg-grid-white/[0.02] pointer-events-none" />
            <div className="absolute bottom-0 left-0 right-0 h-10 bg-gradient-to-t from-black/60 to-transparent pointer-events-none" />

            {/* Flying punched blocks! */}
            {flyingBlocks.map(f => (
              <motion.div
                key={f.id}
                initial={{ x: f.startX, y: 220, opacity: 1, rotate: 0 }}
                animate={{ x: f.flyX, y: f.flyY + 280, opacity: 0, rotate: f.rotate }}
                transition={{ duration: 0.5, ease: 'easeOut' }}
                className="absolute left-1/2 -ml-[55px] w-[110px] h-[46px] rounded-xl border border-red-500/40 bg-zinc-950/95 flex flex-col items-center justify-center p-1 pointer-events-none z-10 shadow-lg text-[9px] text-red-300"
              >
                <span className="text-lg leading-none mb-0.5">{f.habitType.emoji}</span>
                <span className="font-extrabold truncate max-w-[90px]">{isEn ? f.habitType.titleEn : f.habitType.titleFa}</span>
              </motion.div>
            ))}

            {/* Tower Frame Stack */}
            <div className="absolute bottom-5 left-1/2 -translate-x-1/2 w-[120px] h-full z-10 flex flex-col justify-end pointer-events-none">
              
              {/* Inner Steel center column scaffold background */}
              <div className="absolute left-1/2 -translate-x-1/2 top-0 bottom-0 w-3 bg-zinc-800 border-x border-zinc-700/50" />

              {/* Stack blocks with dynamic layout animations */}
              <AnimatePresence>
                {blocks.map((block, index) => {
                  return (
                    <motion.div
                      key={block.id}
                      layout
                      initial={{ opacity: 0, y: -40, scale: 0.8 }}
                      animate={{ opacity: 1, y: 0, scale: 1 }}
                      exit={{ opacity: 0, scale: 0.8 }}
                      transition={{ type: 'spring', stiffness: 500, damping: 24 }}
                      style={{
                        position: 'absolute',
                        bottom: `${index * 50}px`,
                        height: '46px',
                        width: '110px',
                        left: '50%',
                        marginLeft: '-55px'
                      }}
                      className="pointer-events-none z-10"
                    >
                      {/* Central brick box body */}
                      <div className={`w-full h-full rounded-xl bg-gradient-to-br ${block.habitType.color} border-2 border-slate-700/80 shadow-md flex flex-col items-center justify-center p-1 font-sans`}>
                        <div className="flex items-center gap-1">
                          <span className="text-base select-none">{block.habitType.emoji}</span>
                          <span className="text-[8px] font-black tracking-tight uppercase opacity-90 truncate max-w-[65px] text-white">
                            {isEn ? block.habitType.titleEn : block.habitType.titleFa}
                          </span>
                        </div>
                      </div>

                      {/* Left Obstacle Balcony Shelf */}
                      {block.obstacle === 'left' && (
                        <div className="absolute right-full top-1/2 -translate-y-1/2 mr-1 w-[45px] h-[26px] border border-rose-500/50 rounded-l-lg overflow-hidden flex items-center justify-center shadow-lg relative bg-rose-950/80">
                          {/* Retro hazard stripes */}
                          <div className="absolute inset-x-0 bottom-0 h-1 bg-[repeating-linear-gradient(45deg,#f59e0b,#f59e0b_4px,#111827_4px,#111827_8px)]" />
                          <span className="text-[9px] font-black text-rose-300 select-none">⚡ 🚧</span>
                        </div>
                      )}

                      {/* Right Obstacle Balcony Shelf */}
                      {block.obstacle === 'right' && (
                        <div className="absolute left-full top-1/2 -translate-y-1/2 ml-1 w-[45px] h-[26px] border border-rose-500/50 rounded-r-lg overflow-hidden flex items-center justify-center shadow-lg relative bg-rose-950/80">
                          {/* Retro hazard stripes */}
                          <div className="absolute inset-x-0 bottom-0 h-1 bg-[repeating-linear-gradient(45deg,#f59e0b,#f59e0b_4px,#111827_4px,#111827_8px)]" />
                          <span className="text-[9px] font-black text-rose-300 select-none">🚧 ⚡</span>
                        </div>
                      )}
                    </motion.div>
                  );
                })}
              </AnimatePresence>
            </div>

            {/* Boxer / Lion character avatar */}
            <motion.div
              animate={{
                x: boxerSide === 'left' ? -78 : 78,
                scaleY: boxerState === 'punching' ? 0.8 : 1.0,
                rotate: boxerState === 'punching' ? (boxerSide === 'left' ? -15 : 15) : 0
              }}
              transition={{ type: 'spring', stiffness: 600, damping: 20 }}
              className="absolute bottom-5 left-1/2 -translate-x-1/2 z-20 flex flex-col items-center pointer-events-none"
            >
              <div className="relative">
                {boxerState === 'punching' && (
                  <motion.span 
                    initial={{ scale: 0, x: 0 }}
                    animate={{ 
                      scale: 1.8, 
                      x: boxerSide === 'left' ? 30 : -30 
                    }}
                    className="absolute top-[8px] text-xl pointer-events-none z-30 font-sans"
                    style={{ left: boxerSide === 'left' ? '100%' : 'auto', right: boxerSide === 'right' ? '100%' : 'auto' }}
                  >
                    💥🔥
                  </motion.span>
                )}
                {/* Only flip the Emoji itself so text below it in parent div remains perfectly readable! */}
                <span 
                  className="text-4xl filter drop-shadow-md select-none block transition-transform duration-75"
                  style={{
                    transform: boxerSide === 'left' ? 'scaleX(1)' : 'scaleX(-1)'
                  }}
                >
                  🦁🥊
                </span>
              </div>
              <span className="text-[8px] font-black bg-zinc-950/90 border border-yellow-500/35 text-yellow-400 px-1.5 py-0.5 rounded-full mt-0.5 tracking-wider uppercase">
                {isEn ? 'FIGHTER' : 'قهرمان'}
              </span>
            </motion.div>
          </div>

          {/* Interactive Glove Button Controllers */}
          <div className="flex gap-4 w-full justify-center pt-2 max-w-[280px]" dir="ltr">
            <button
              onClick={() => handlePunch('left')}
              className="flex-1 py-3 bg-rose-700/20 hover:bg-rose-600/30 active:scale-95 border-2 border-rose-500/40 rounded-2xl flex flex-col items-center justify-center gap-0.5 cursor-pointer text-xs font-black p-1 transition-all text-rose-300 animate-in fade-in zoom-in-95 duration-150"
            >
              <span className="text-2xl pt-0.5">🥊 ◀</span>
              <span className="text-[10px] font-bold">{isEn ? 'Punch from Left' : 'مشت از چپ'}</span>
            </button>

            <button
              onClick={() => handlePunch('right')}
              className="flex-1 py-3 bg-rose-700/20 hover:bg-rose-600/30 active:scale-95 border-2 border-rose-500/40 rounded-2xl flex flex-col items-center justify-center gap-0.5 cursor-pointer text-xs font-black p-1 transition-all text-rose-300 animate-in fade-in zoom-in-95 duration-150"
            >
              <span className="text-2xl pt-0.5">▶ 🥊</span>
              <span className="text-[10px] font-bold">{isEn ? 'Punch from Right' : 'مشت از راست'}</span>
            </button>
          </div>

          <span className="text-[9px] text-app-muted block font-sans">
            {isEn ? 'Tip: Laptop Keyboard Arrow keys work perfectly!' : 'نکته: از کلیدهای چپ و راست کیبورد دسکتاپ هم می‌توانید استفاده کنید!'}
          </span>
        </div>
      )}

      {gameState === 'ended' && (
        <div className="flex flex-col items-center gap-4 py-8 max-w-sm font-sans animate-in fade-in zoom-in-95 duration-200">
          <span className="text-4xl text-yellow-500">🏆</span>
          <h3 className="font-sans font-black text-base text-app-text">
            {isEn ? 'Tower Smashed!' : 'نبرد به پایان رسید!'}
          </h3>
          <p className="text-xs text-app-muted px-4">
            {isEn 
              ? `You successfully smashed ${score} bad habit layers in the habit tower!` 
              : `خسته نباشید قهرمان! شما توانستید ${score} لایه از عادات مضر و تنبلی‌های خود را مقتدرانه متلاشی کنید.`}
          </p>
          <div className="bg-app-widget border border-app-border rounded-xl p-3 w-full flex items-center justify-between text-xs font-sans">
            <span className="text-app-muted">{isEn ? 'XP Awarded:' : 'میزان کسب امتیاز پیشرفت:'}</span>
            <span className="text-yellow-500 font-bold font-mono">+{Math.min(50, Math.floor(score * 0.4))} XP</span>
          </div>

          <button
            onClick={initGame}
            className="px-6 py-2.5 bg-yellow-500 hover:bg-yellow-600 font-black text-xs text-black rounded-xl shadow-md transition-all cursor-pointer flex items-center gap-1 hover:scale-105"
          >
            <RotateCcw size={12} />
            <span>{isEn ? 'Smash Again' : 'شروع مجدد نبرد'}</span>
          </button>
        </div>
      )}
    </div>
  );
}

